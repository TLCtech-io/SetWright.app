for select using (public.auth_member_tier(id) is not null);
create policy ensemble_update on public.ensemble
for update using (public.auth_member_tier(id) = 'director')
with check (public.auth_member_tier(id) = 'director');

-- member: read the roster of your ensembles, plus your own row anywhere. The second branch is
-- what lets a member see their seat in a tenant whose tier no longer resolves. The director
-- writes the roster. A member edits their own name and range through update_my_profile, not
-- here, so they cannot touch their own tier.
create policy member_read on public.member
for select using (public.auth_member_tier(ensemble_id) is not null or user_id = auth.uid());
