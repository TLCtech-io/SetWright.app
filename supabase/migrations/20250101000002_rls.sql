-- setlist: any read still requires active membership of THIS row's ensemble. That is the
-- tenant boundary and it gates every branch. Drop it from one branch and the bare
-- published/performed/share_draft predicate matches rows in every ensemble and leaks across
-- tenants. Within the tenant a director reads all; a member reads a set that is published,
-- performed, or a draft the director chose to share. draft_order and published_order ride this
-- row, so this one policy covers both member read paths with no separate policy.
create policy setlist_read on public.setlist
for select using (
    public.auth_member_tier(ensemble_id) is not null
    and (
        public.auth_member_tier(ensemble_id) = 'director'
        or published_at is not null
        or status = 'performed'
        or share_draft
    )
);
create policy setlist_write on public.setlist
for all using (public.auth_member_tier(ensemble_id) = 'director')
with check (public.auth_member_tier(ensemble_id) = 'director');

-- setlist_item / setlist_break: same tenant guard, then readable when the parent setlist is.
-- The subquery names the parent's gate explicitly rather than leaning on setlist_read composing
-- through. Note the parent gate here is published-or-performed only, deliberately narrower than
-- setlist_read: a shared draft is read from the setlist row's snapshot, never from these child
-- rows, so a member sees no draft item or break.
create policy setlist_item_read on public.setlist_item
for select using (
    public.auth_member_tier(ensemble_id) is not null
    and (
        public.auth_member_tier(ensemble_id) = 'director'
        or exists (
            select 1 from public.setlist s
            where s.ensemble_id = setlist_item.ensemble_id
            and s.id = setlist_item.setlist_id
            and (s.published_at is not null or s.status = 'performed')
        )
    )
);
create policy setlist_item_write on public.setlist_item
for all using (public.auth_member_tier(ensemble_id) = 'director')
with check (public.auth_member_tier(ensemble_id) = 'director');

create policy setlist_break_read on public.setlist_break
for select using (
    public.auth_member_tier(ensemble_id) is not null
    and (
        public.auth_member_tier(ensemble_id) = 'director'
        or exists (
            select 1 from public.setlist s
            where s.ensemble_id = setlist_break.ensemble_id
            and s.id = setlist_break.setlist_id
            and (s.published_at is not null or s.status = 'performed')
        )
    )
);
create policy setlist_break_write on public.setlist_break
for all using (public.auth_member_tier(ensemble_id) = 'director')
with check (public.auth_member_tier(ensemble_id) = 'director');


-- ----------------------------------------------------------------------------
-- casting: ownership is per column. The director owns the assignment, is_primary, and their
-- own private assessment; the member owns self_reported_confidence. RLS is row-level, so it
-- cannot split that.
--
-- Writes: the director writes the row here. Members write their own confidence through
-- set_my_confidence (006), never directly.
-- Reads: members have no SELECT policy on the base table and reach castings only through
-- casting_visible, which nulls other people's confidence unless the ensemble is set to
-- 'shared'. That makes 'private' actually hold rather than being a UI nicety.
-- ----------------------------------------------------------------------------

create policy casting_insert on public.casting
for insert with check (public.auth_member_tier(ensemble_id) = 'director');
create policy casting_update on public.casting
for update using (public.auth_member_tier(ensemble_id) = 'director')
with check (public.auth_member_tier(ensemble_id) = 'director');
create policy casting_delete on public.casting
for delete using (public.auth_member_tier(ensemble_id) = 'director');

-- Load-bearing, and easy to mistake for redundancy. A filtered casting write
-- (DELETE or UPDATE ... WHERE part_id in (...)) needs its target rows visible through a SELECT
-- policy, not just the DELETE/UPDATE USING clause. Without this the director's own writes would
-- silently match zero rows. The second reason is plainer: the director owns this data and the
-- view exposes all of it to them anyway.
create policy casting_select_director on public.casting
for select using (public.auth_member_tier(ensemble_id) = 'director');


-- ----------------------------------------------------------------------------
-- casting_visible: the member read path for castings.
--
-- The view runs with its owner's rights and bypasses casting's RLS, so the WHERE clause is the
-- tenant guard and the CASE arms are the confidence guard. security_barrier keeps a
-- caller-supplied predicate from being evaluated ahead of those quals.
--
-- The barrier was measured before it shipped, because a barrier view refuses to push
-- caller quals down unless they are leakproof and the drafter's hottest read goes through here.
-- On the query shape the drafter's castings CTE uses, the ensemble filter reaches the base scan
-- either way, and with the barrier it reaches it as an index condition on idx_casting_ensemble
-- rather than a post-filter. The uncorrelated sub-select becomes an InitPlan evaluated once, so
-- the qual reduces to a leakproof equality that is pushdown-safe. A correlated sub-select would
-- not be, which is what the general warning about barrier views is about. The cost that remains
-- is that genuinely non-pushdown-safe quals now stay outside the view.
-- ----------------------------------------------------------------------------

create view public.casting_visible with (security_barrier = true) as
select
c.id, c.ensemble_id, c.part_id, c.member_id, c.is_primary,
case
when public.auth_is_self(c.member_id)                    then c.self_reported_confidence
when public.auth_member_tier(c.ensemble_id) = 'director' then c.self_reported_confidence
when e.confidence_visibility = 'shared'                  then c.self_reported_confidence
else null
end as self_reported_confidence,
-- The director's private read of each cover, and the date it was confirmed solid. A member
-- never sees the director's assessment of anyone, including themselves. This is the read path
-- the learning tracker and the casting editor use.
case when public.auth_member_tier(c.ensemble_id) = 'director' then c.director_assessed end as director_assessed,
case when public.auth_member_tier(c.ensemble_id) = 'director' then c.learned_at        end as learned_at,
c.created_at, c.updated_at, c.created_by, c.updated_by
from public.casting c
join public.ensemble e on e.id = c.ensemble_id
where public.auth_member_tier(c.ensemble_id) is not null;

-- Members reach castings only through this view. The base-table SELECT privilege from the
-- blanket grant stays in place so casting_select_director and the director's filtered writes
-- can resolve their rows; a member matches no SELECT policy there, so a direct read of casting
-- returns zero rows even with the privilege.
grant select on public.casting_visible to authenticated;
