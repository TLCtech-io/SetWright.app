-- ============================================================================
-- Row-level security: the auth helpers, table privileges, and every policy.
--
-- Model
--   Isolation is by membership, not by a session variable. A user reaches a row when they
--   hold an active member row in that row's active ensemble. Their tier on that membership
--   decides writes. The app narrows a screen by filtering on ensemble_id; RLS only draws
--   the hard boundary.
--
-- Ordering inside this file is load-bearing in three places.
--   1. The three helper functions come first. Every policy below calls one of them, and a
--      policy expression is parsed at creation time, so the functions must already exist.
--   2. The blanket table grant runs before casting_visible is created. `grant ... on all
--      tables in schema public` includes views, and the view is meant to be select-only for
--      authenticated. Creating it after the blanket grant, then granting select on it
--      explicitly, is what keeps it that way.
--   3. app_user's update privilege is narrowed to two columns after the blanket grant, and
--      invite_rate_event is stripped back to deny-all after it. Both are subtractions from
--      the blanket, so they cannot precede it.
--
-- Ordering against the other files: 001 creates every table this file grants on and guards.
-- 003 through 007 define triggers and RPCs that call these helpers, so they come after.
--
-- Policies are written out one per statement rather than generated by a loop over a table
-- array. The loop was shorter, but five of the policies it produced were later replaced with
-- narrower reads (program, program_item, setlist, setlist_item, setlist_break), so a loop
-- here would have to be followed by a set of overrides, and the final shape of any one table
-- would live in two places. Written out, each policy's live form is one greppable statement
-- that lines up with one line of the catalog. The cost is 34 near-identical statements for
-- the common member-reads-director-writes pattern. On a security surface that is the right
-- trade: this is the file you read to answer "who can see this row".
--
-- Two properties to keep in mind when editing anything below.
--   - Permissive policies are OR'd. Adding a policy to a table can only widen access, never
--     narrow it. To narrow a read you replace the existing policy, you do not add one.
--   - A membership check must gate EVERY branch of a multi-branch read. A bare predicate
--     like `published_at is not null` sitting beside the tenant check under an OR matches
--     rows in every ensemble.
-- ============================================================================


-- ----------------------------------------------------------------------------
-- The auth helpers.
--
-- The recursion trap is why these are SECURITY DEFINER. A policy that guards a row has to
-- read the member table to check membership. The member table needs the same guard, so its
-- policy would read member to decide whether you can read member. That recurses. These
-- functions read membership with RLS turned off inside them, which breaks the cycle. Every
-- policy in this file leans on one of them.
--
-- Hardening that applies to all three: search_path is pinned to `pg_catalog, pg_temp` (not
-- public, and pg_temp last) and every table they touch is schema-qualified, so a caller with
-- temp-object rights cannot shadow a relation these definer functions trust.
--
-- Both membership helpers require the member row to be active AND the ensemble to be active.
-- Without the ensemble check, archiving or suspending a tenant would be cosmetic: every
-- policy built on the tier would keep passing. With it, archiving freezes the tenant
-- transparently, everywhere at once.
-- ----------------------------------------------------------------------------

-- The caller's tier in an ensemble, or null if they are not an active member of it.
create or replace function public.auth_member_tier(p_ensemble uuid)
returns text
language sql
stable
security definer
set search_path = pg_catalog, pg_temp
as $$
select m.permission_tier
from public.member m
join public.ensemble e on e.id = m.ensemble_id
where m.ensemble_id = p_ensemble
and m.user_id = auth.uid()
and m.status = 'active'
and e.status = 'active'
limit 1;
$$;

-- True when the given member row belongs to the caller. For self-writes.
-- Self-READ does not use this: member_read has its own `user_id = auth.uid()` branch, so a
-- member can still see their own row in an archived tenant even though they cannot write it.
create or replace function public.auth_is_self(p_member uuid)
returns boolean
language sql
stable
security definer
set search_path = pg_catalog, pg_temp
as $$
select exists (
    select 1 from public.member m
    join public.ensemble e on e.id = m.ensemble_id and e.status = 'active'
    where m.id = p_member and m.user_id = auth.uid()
    and m.status = 'active'
);
$$;

-- True when the caller is a platform admin (operator or sales). This gates the /admin surface
-- and the admin-invite path, nothing else. It grants NO cross-tenant data access: no policy in
-- this file references it, so a platform admin still cannot read another ensemble's rows. The
-- flag is set out of band by SQL; no app route writes it. An anonymous caller coalesces to false.
create or replace function public.auth_is_platform_admin()
returns boolean
language sql
stable
security definer
set search_path = pg_catalog, pg_temp
as $$
select coalesce(
    (select u.is_platform_admin from public.app_user u where u.id = auth.uid()),
    false
);
$$;

revoke all on function public.auth_is_platform_admin() from public;
grant  execute on function public.auth_is_platform_admin() to authenticated;


-- ----------------------------------------------------------------------------
-- Base-table privileges for the PostgREST roles.
--
-- Migrations run as `postgres`, whose default privileges confer only
-- REFERENCES/TRIGGER/TRUNCATE/MAINTAIN on new tables to the API roles, not read or write
-- (only supabase_admin's default privileges do that). Without this grant an authenticated
-- user hits "permission denied for table" before RLS is ever consulted.
--
-- These grants decide only whether a role may touch a table at all; the policies below decide
-- which rows. A non-director's write matches no policy and touches zero rows. anon is granted
-- nothing here and so reaches no tenant table.
-- ----------------------------------------------------------------------------

grant select, insert, update, delete on all tables in schema public to authenticated;

-- app_user carries is_platform_admin, and app_user_update lets a user update their own row.
-- A blanket table-level UPDATE plus that policy would let anyone PATCH is_platform_admin = true
-- on themselves through PostgREST and self-promote. Column privileges are checked independently
-- of RLS, so pin authenticated's UPDATE to the two self-editable columns. The admin flag is then
-- unwritable by authenticated at all. It is not writable by service_role either, which holds no
-- grant on app_user and cannot even read it, so the only way in is a superuser connection. The app never
-- PATCHes app_user directly (profile edits go through the update_my_profile definer RPC), so this
-- narrows nothing the app relies on.
revoke update on public.app_user from authenticated;
grant  update (email, display_name) on public.app_user to authenticated;

-- invite_rate_event is deny-all: RLS on (below) with no policies, and no grants to authenticated
-- or anon, so PostgREST cannot touch it. The rate-limit definer functions are the only access
-- path. This revoke undoes the blanket grant above for this one table.
revoke all on public.invite_rate_event from authenticated, anon;


